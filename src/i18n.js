export function translateText(language, text, params = {}) {
  if (text == null) {
    return text;
  }
  if (typeof text !== "string") {
    return text;
  }
  const normalized = normalizeLanguage(language);
  if (normalized === "en") {
    return format(text, params);
  }
  return format(EXACT_ZH[text] ?? text, params);
}

export function formatMessage(language, key, params = {}) {
  const normalized = normalizeLanguage(language);
  const template =
    KEYED_MESSAGES[normalized]?.[key] ??
    KEYED_MESSAGES.en[key] ??
    "";
  return format(template, params);
}

